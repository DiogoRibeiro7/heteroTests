
# --- Wang-Zhou prototype: Table 1 of the working paper ----------------------------

csv_wr <- file.path("inst", "validation", "variance-form-wz-reproduction.csv")
if (!file.exists(csv_wr)) csv_wr <- "variance-form-wz-reproduction.csv"
if (file.exists(csv_wr)) {
  wr <- utils::read.csv(csv_wr, stringsAsFactors = FALSE)
  # The paper's rates rest on 400 replications.
  paper_reps <- 400
  pooled <- (wr$rejection_rate * wr$effective + wr$paper_rate * paper_reps) /
    (wr$effective + paper_reps)
  se_diff <- sqrt(pooled * (1 - pooled) * (1 / wr$effective + 1 / paper_reps))
  wr$within <- abs(ifelse(se_diff > 0, (wr$rejection_rate - wr$paper_rate) / se_diff, 0)) <=
    stats::qnorm(0.995)
  wr$diff_pts <- 100 * (wr$rejection_rate - wr$paper_rate)
  pts <- function(x) sprintf("%.1f", round(x, 1) + 0)
  hs <- sort(unique(wr$h[wr$test == "wang_zhou"]))
  kernels <- c(gaussian = "Gaussian", epanechnikov = "Epanechnikov")
  for (k in intersect(names(kernels), unique(wr$kernel))) {
    rows <- wr[wr$kernel == k, , drop = FALSE]
    cat(sprintf("\n### Working paper Table 1, %s kernel: here (paper)\n\n", kernels[[k]]))
    cat("| sigma(x) | n | ", paste(sprintf("T_n, h = %.2f", hs), collapse = " | "),
        " | Wald |\n", sep = "")
    cat("| --- | ---: | ", paste(rep("---:", length(hs) + 1L), collapse = " | "), " |\n", sep = "")
    for (model in c("(1)", "(2)", "(3)")) {
      for (n in sort(unique(rows$n))) {
        at <- function(test, h = NA) {
          hit <- rows$model == model & rows$n == n & rows$test == test &
            (is.na(h) | (!is.na(rows$h) & abs(rows$h - h) < 1e-9))
          sprintf("%.3f (%.3f)", rows$rejection_rate[hit][1L], rows$paper_rate[hit][1L])
        }
        cells <- c(vapply(hs, function(h) at("wang_zhou", h), character(1)), at("wald"))
        cat(sprintf("| %s | %d | %s |\n", model, n, paste(cells, collapse = " | ")))
      }
    }
  }
  cat("\n### Working paper Table 1, by kernel\n\n")
  cat("| Kernel | Test | Null rates within the interval | Alternative rates within the interval |",
      "Alternatives, here less the paper, percentage points |\n")
  cat("| --- | --- | ---: | ---: | --- |\n")
  for (k in intersect(names(kernels), unique(wr$kernel))) {
    for (test in c("wang_zhou", "wald")) {
      r <- wr[wr$kernel == k & wr$test == test, , drop = FALSE]
      null_r <- r$model == "(1)"
      cat(sprintf("| %s | %s | %d of %d | %d of %d | %s on average, %s to %s |\n",
                  kernels[[k]], if (test == "wald") "Wald" else "T_n",
                  sum(r$within & null_r), sum(null_r), sum(r$within & !null_r), sum(!null_r),
                  pts(mean(r$diff_pts[!null_r])), pts(min(r$diff_pts[!null_r])),
                  pts(max(r$diff_pts[!null_r]))))
    }
  }
  cat(sprintf(
    paste0(
      "\nReplications: %d here and %d in the paper, with B = %d bootstrap samples and the ",
      "p-value (1 + #) / (B + 1). A rate is within the interval when it is within the 99%% ",
      "interval of the difference between two independent estimates.\n"
    ),
    wr$replications[1], paper_reps, wr$bootstrap[!is.na(wr$bootstrap)][1L]))
  cat("\n<!-- generated by make-table.R; do not edit the numbers by hand -->\n\n")
  for (k in intersect(names(kernels), unique(wr$kernel))) {
    r <- wr[wr$kernel == k & wr$test == "wang_zhou", , drop = FALSE]
    null_r <- r$model == "(1)"
    cat(sprintf(
      paste0(
        "With the %s kernel, %d of the %d rates of T_n are within the interval: %d of %d under ",
        "the null hypothesis, where the rates here run from %.3f to %.3f, and %d of %d under ",
        "the alternatives.\n"
      ),
      kernels[[k]], sum(r$within), nrow(r), sum(r$within & null_r), sum(null_r),
      min(r$rejection_rate[null_r]), max(r$rejection_rate[null_r]),
      sum(r$within & !null_r), sum(!null_r)))
  }
}

# --- Wang-Zhou prototype: size and power ---------------------------------------------

csv_ws <- file.path("inst", "validation", "variance-form-wz-size-power.csv")
if (!file.exists(csv_ws)) csv_ws <- "variance-form-wz-size-power.csv"
csv_dn <- file.path("inst", "validation", "variance-form-dnvk-size-power.csv")
if (!file.exists(csv_dn)) csv_dn <- "variance-form-dnvk-size-power.csv"
if (file.exists(csv_ws)) {
  ws <- utils::read.csv(csv_ws, stringsAsFactors = FALSE)
  main_c <- 0.15
  ws$key <- ifelse(ws$test %in% c("wz_bootstrap", "wz_asymptotic"),
                   paste0(ws$test, "@", ws$bandwidth), ws$test)
  if (file.exists(csv_dn)) {
    dn <- utils::read.csv(csv_dn, stringsAsFactors = FALSE)
    dn <- dn[dn$block == "main" & dn$test == "dnvk_cm", , drop = FALSE]
    dn$key <- "dnvk_cm"
    dn$bandwidth <- NA_real_
    dn$kernel <- NA_character_
    keep_cols <- intersect(names(ws), names(dn))
    both <- rbind(ws[, keep_cols], dn[, keep_cols])
  } else {
    both <- ws
  }
  tests <- c(
    "wz_bootstrap@0.15" = "Wang-Zhou, bootstrap, prototype",
    "wz_asymptotic@0.15" = "Wang-Zhou, normal reference (not in the paper)",
    dnvk_cm = "Dette-Neumeyer-Van Keilegom prototype (other samples)",
    form_test_x = "`performVarianceFormTest(var_formula = ~ x)`",
    form_test_default = "`performVarianceFormTest()`"
  )
  tests <- tests[names(tests) %in% both$key]
  truth_order <- c("constant", "exponential", "power", "linear", "quadratic", "wave")
  sizes <- sort(unique(ws$n))
  rate_of <- function(rows, ...) {
    keys <- list(...)
    hit <- rep(TRUE, nrow(rows))
    for (k in names(keys)) hit <- hit & rows[[k]] == keys[[k]]
    if (any(hit)) rows$rejection_rate[hit][1L] else NA_real_
  }
  fmt3 <- function(x) ifelse(is.na(x), "--", sprintf("%.3f", x))

  cat("\n### Wang-Zhou prototype beside the other tests, size\n\n")
  cat("| Form tested | True variance | Test | ",
      paste(c(sprintf("Gaussian, n = %d", sizes), sprintf("t5, n = %d", sizes)), collapse = " | "),
      " |\n", sep = "")
  cat("| --- | --- | --- | ", paste(rep("---:", 2L * length(sizes)), collapse = " | "), " |\n",
      sep = "")
  for (form in c("exponential", "power")) {
    nulls <- unique(ws$truth[ws$form == form & ws$hypothesis == "null"])
    for (truth in intersect(truth_order, nulls)) {
      label <- ws$truth_label[ws$truth == truth][1L]
      for (key in names(tests)) {
        cells <- c(
          vapply(sizes, function(n) {
            fmt3(rate_of(both, form = form, truth = truth, key = key, errors = "normal", n = n))
          }, character(1)),
          vapply(sizes, function(n) {
            fmt3(rate_of(both, form = form, truth = truth, key = key, errors = "t5", n = n))
          }, character(1))
        )
        cat(sprintf("| %s | `%s` | %s | %s |\n", form, label, tests[[key]],
                    paste(cells, collapse = " | ")))
      }
    }
  }

  for (errors in c("normal", "t5")) {
    cat(sprintf("\n### Wang-Zhou prototype beside the other tests, power, %s errors\n\n",
                if (errors == "normal") "Gaussian" else "t5"))
    cat("| Form tested | True variance | Test | ",
        paste(sprintf("n = %d", sizes), collapse = " | "), " |\n", sep = "")
    cat("| --- | --- | --- | ", paste(rep("---:", length(sizes)), collapse = " | "), " |\n",
        sep = "")
    for (form in c("exponential", "power")) {
      alts <- unique(ws$truth[ws$form == form & ws$hypothesis == "alternative"])
      for (truth in intersect(truth_order, alts)) {
        label <- ws$truth_label[ws$truth == truth][1L]
        for (key in names(tests)) {
          cells <- vapply(sizes, function(n) {
            fmt3(rate_of(both, form = form, truth = truth, key = key, errors = errors, n = n))
          }, character(1))
          cat(sprintf("| %s | `%s` | %s | %s |\n", form, label, tests[[key]],
                      paste(cells, collapse = " | ")))
        }
      }
    }
  }

  bw <- ws[ws$test == "wz_bootstrap" & ws$errors == "normal", , drop = FALSE]
  cs <- sort(unique(bw$bandwidth))
  bw_sizes <- sort(unique(bw$n[bw$bandwidth != main_c]))
  if (length(cs) > 1L && length(bw_sizes)) {
    cat("\n### Wang-Zhou prototype, constant of the bandwidth, Gaussian errors\n\n")
    cat("| Form tested | True variance | Hypothesis | ",
        paste(unlist(lapply(bw_sizes, function(n) sprintf("n = %d, c = %.2f", n, cs))),
              collapse = " | "), " |\n", sep = "")
    cat("| --- | --- | --- | ", paste(rep("---:", length(cs) * length(bw_sizes)), collapse = " | "),
        " |\n", sep = "")
    for (form in c("exponential", "power")) {
      for (truth in intersect(truth_order, unique(bw$truth[bw$form == form]))) {
        rows <- bw[bw$form == form & bw$truth == truth, , drop = FALSE]
        cells <- unlist(lapply(bw_sizes, function(n) {
          vapply(cs, function(cc) fmt3(rate_of(rows, n = n, bandwidth = cc)), character(1))
        }))
        cat(sprintf("| %s | `%s` | %s | %s |\n", form, rows$truth_label[1L],
                    rows$hypothesis[1L], paste(cells, collapse = " | ")))
      }
    }
  }

  reps <- sort(unique(ws$replications))
  cat(sprintf(
    paste0(
      "\nReplications: %s, with B = %d bootstrap samples for the prototype and the %s kernel. ",
      "Nominal level: 0.05. Monte Carlo standard error at the nominal level: %s. The rows of ",
      "the Dette-Neumeyer-Van Keilegom prototype come from `variance-form-dnvk-size-power.csv`, ",
      "on other samples of the same designs.\n"
    ),
    paste(reps, collapse = " and "), ws$bootstrap[!is.na(ws$bootstrap)][1L],
    ws$kernel[!is.na(ws$kernel)][1L],
    paste(sprintf("%.4f", sqrt(0.05 * 0.95 / reps)), collapse = " and ")))

  # The generated summary. The release gate applies to the Gaussian null cells,
  # each at its own number of replications.
  nulls <- both[both$hypothesis == "null" & both$key %in% names(tests), , drop = FALSE]
  half <- stats::qnorm(0.995) * sqrt(0.05 * 0.95 / nulls$replications)
  in_band <- abs(nulls$rejection_rate - 0.05) <= half
  gaussian <- nulls$errors == "normal"
  cat("\n<!-- generated by make-table.R; do not edit the numbers by hand -->\n\n")
  for (key in names(tests)) {
    keep_g <- gaussian & nulls$key == key
    keep_t <- !gaussian & nulls$key == key
    cat(sprintf(
      paste0(
        "- %s: %d of the %d Gaussian null cells inside the 99%% interval at their replications ",
        "(rates %.3f to %.3f); %d of the %d t5 null cells (rates %.3f to %.3f).\n"
      ),
      tests[[key]], sum(in_band & keep_g), sum(keep_g),
      min(nulls$rejection_rate[keep_g]), max(nulls$rejection_rate[keep_g]),
      sum(in_band & keep_t), sum(keep_t),
      min(nulls$rejection_rate[keep_t]), max(nulls$rejection_rate[keep_t])))
  }
  outside <- which(!in_band & gaussian & nulls$key == "wz_bootstrap@0.15")
  if (length(outside)) {
    cat("\nGaussian null cells of the Wang-Zhou bootstrap test outside that interval:\n\n")
    for (i in outside) {
      cat(sprintf("- %s form, `%s`, n = %d: %.4f.\n", nulls$form[i], nulls$truth_label[i],
                  nulls$n[i], nulls$rejection_rate[i]))
    }
  }

  alt <- both[both$hypothesis == "alternative", , drop = FALSE]
  cells <- unique(alt[alt$key == "wz_bootstrap@0.15", c("form", "truth", "errors", "n")])
  gap <- function(other) {
    vapply(seq_len(nrow(cells)), function(i) {
      at <- function(key) {
        rate_of(alt, form = cells$form[i], truth = cells$truth[i], errors = cells$errors[i],
                n = cells$n[i], key = key)
      }
      100 * (at("wz_bootstrap@0.15") - at(other))
    }, numeric(1))
  }
  for (other in intersect(c("form_test_x", "dnvk_cm"), names(tests))) {
    g <- gap(other)
    cat(sprintf(
      paste0(
        "\nIn the %d alternative cells the Wang-Zhou bootstrap test rejects more often than %s ",
        "in %d; by true variance, the difference in percentage points:\n\n"
      ),
      length(g), tests[[other]], sum(g > 0, na.rm = TRUE)))
    for (truth in intersect(truth_order, unique(cells$truth))) {
      keep <- cells$truth == truth
      cat(sprintf("- `%s`: %s to %s.\n", alt$truth_label[alt$truth == truth][1L],
                  sprintf("%.1f", min(g[keep], na.rm = TRUE)),
                  sprintf("%.1f", max(g[keep], na.rm = TRUE))))
    }
  }

  proto <- ws[ws$test == "wz_bootstrap" & abs(ws$bandwidth - main_c) < 1e-9, , drop = FALSE]
  cat(sprintf(
    paste0(
      "\nThe pseudo-likelihood fit did not settle, so that the prototype could not be computed, ",
      "in %d of the %d samples, and in %.3f%% of the bootstrap samples, which are left out of ",
      "the bootstrap distribution.\n"
    ),
    sum(proto$failures), sum(proto$replications),
    100 * sum(proto$bootstrap_failures) / sum(proto$effective * proto$bootstrap)))
}
